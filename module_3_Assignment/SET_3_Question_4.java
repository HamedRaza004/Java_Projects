public class SET_3_Question_4 {
    public static void main(String[] args) {
        // Math.random() - returns a random double between 0.0 and 1.0
        System.out.println("Random number: " + Math.random());

        // Math.abs() - returns the absolute value
        System.out.println("Absolute value of -10: " + Math.abs(-10));

        // Math.pow() - returns the value of the first argument raised to the power of the second argument
        System.out.println("2 to the power of 3: " + Math.pow(2, 3));
    }
}
